import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDir = dirname(fileURLToPath(import.meta.url))
const docsDir = join(scriptsDir, '..')
const pkgDir = join(docsDir, '..')

const REPO_BLOB = 'https://github.com/rasuvaeff/yii3-mcp/blob/master/'

function rewriteRelativeLinks(markdown) {
    return markdown.replace(/\]\((?!https?:|#|\/)([^)]+)\)/g, (_match, target) => `](${REPO_BLOB}${target})`)
}

// ROADMAP.md and llms.txt are single sources of truth in the core package —
// import them whole rather than duplicating their content by hand in docs/.
// (INTEGRATION-MCP.md is deliberately NOT imported: it's an internal Russian
// runbook, not public English protocol documentation — protocol.md is
// hand-written instead, grounded in src/ and AGENTS.md.)
const directImports = [
    { source: 'ROADMAP.md', file: 'roadmap.md', title: 'Roadmap' },
    { source: 'llms.txt', file: 'llms.md', title: 'llms.txt reference' },
]

for (const entry of directImports) {
    const raw = readFileSync(join(pkgDir, entry.source), 'utf8')
    const body = rewriteRelativeLinks(raw)
    const outPath = join(docsDir, entry.file)
    mkdirSync(dirname(outPath), { recursive: true })
    writeFileSync(
        outPath,
        `---\ntitle: ${JSON.stringify(entry.title)}\n---\n\n` +
            `<!-- AUTO-GENERATED by docs/scripts/aggregate.mjs from ${entry.source} — do not edit this file directly. -->\n\n` +
            body.trimStart() +
            '\n',
        'utf8',
    )
}

console.log(`Imported ${directImports.length} source file(s) whole into docs/**.`)
